//! The reversal for the MINT half of the coupled seat: a services refusal family
//! body is produced only by a pass inside the plane that established its issues.
//!
//! A private seat closes the LITERAL and nothing else. A road that takes an
//! issue and hands back a refusal is the loading dock behind that fence: any
//! holder of an issue mints a body no pass raised, and any holder of the
//! borrowed body clones its issues out and reseats them through the same road.
//! The record either produces is indistinguishable from one a seam returned.
//!
//! # This fixture names the roads; the LAW holds the population
//!
//! What is written below is every mint the seven families declare today — three
//! for `ProjectionPlanning`, two for `TemplateConstruction`, one each for
//! `ProjectionClosureRefusal`, `ExplanationCoverage`, `TriggerViewComposition`,
//! `CompositionRootDeclaration` and `RefusalDeriveRefusal`. Ten roads, and
//! restoring `pub` on ANY one of them makes that line resolve, changes this
//! file's diagnostics, and fails the fixture. That is a real refusal and it is
//! what a compile-fail fixture is for.
//!
//! It is not the universal statement, and it never could be: a list names the
//! roads that exist, so a family added tomorrow with a public mint leaves this
//! file compiling exactly as it does now. A repository law used to try to close
//! that gap by deriving the population — every closed record some road refuses
//! with, joined against every road handing one back — and it was wrong
//! repeatedly, because answering it means resolving types, following aliases,
//! deciding what a receiver stands for, and inferring reachability. It is
//! deleted.
//!
//! What stands in its place is structural. Each body is DECLARED in a `seat`
//! module inside its home's `type_guard.rs`, and `cargo xtask check`'s
//! `seat-modules-carry-nothing-else` holds that module to carrying the record
//! and inherent implementations of it and nothing else — a question about item
//! kinds, resolving nothing. So the set of code that can reach a private seat is
//! a module read in one screen rather than a file of dozens of types, and every
//! road outside it is `E0451` or `E0616` from the compiler.
//!
//! The paths are REFERENCED rather than called on purpose. Privacy is settled at
//! resolution, so a reference establishes the claim without constructing
//! arguments — and arguments constructed here would be testing the argument
//! types instead of the visibility.

use threadpak_macroc::{
    CompositionRootDeclaration, ExplanationCoverage, ProjectionClosureRefusal, ProjectionPlanning,
    RefusalDeriveRefusal, RenderedImplementation, TemplateConstruction, TriggerViewComposition,
};

fn main() {
    let _planning_one = ProjectionPlanning::established;
    let _planning_many = ProjectionPlanning::co_established;
    let _planning_bound = ProjectionPlanning::bound_exceeded;
    let _template_one = TemplateConstruction::established;
    let _template_many = TemplateConstruction::co_established;
    let _closure = ProjectionClosureRefusal::<RenderedImplementation>::established;
    let _coverage = ExplanationCoverage::established;
    let _trigger_view = TriggerViewComposition::established;
    let _composition = CompositionRootDeclaration::established;
    let _capture = RefusalDeriveRefusal::established;
}
